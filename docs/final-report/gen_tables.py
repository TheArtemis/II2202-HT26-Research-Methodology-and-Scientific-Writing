#!/usr/bin/env python3
"""Generate detailed RQ1 appendix tables from the report's 900-trial campaign."""

import json
from collections import defaultdict
from pathlib import Path
from statistics import mean, stdev

OUT = Path(__file__).resolve().parent
DATA = OUT.parents[1] / "results/campaigns/full-20261014-hb500-noprevote/merged"
DELAYS = [("500µs", "0.5"), ("5ms", "5"), ("20ms", "20")]
MODES = ("direct", "forwarding")


def table(caption, label, columns, heading, rows):
    return "\n".join([
        r"\begin{table}[H]",
        r"  \centering",
        "  \\caption{" + caption + "}",
        "  \\label{" + label + "}",
        "  \\begin{tabular}{" + columns + "}",
        r"    \toprule",
        "    " + heading + r" \\",
        r"    \midrule",
        *["    " + " & ".join(row) + r" \\" for row in rows],
        r"    \bottomrule",
        r"  \end{tabular}",
        r"\end{table}",
        "",
    ])


def mean_sd(values):
    if not values:
        return "--"
    return f"\\({mean(values):.2f} \\pm {stdev(values):.2f}\\)"


def main():
    rows = [json.loads(line) for line in (DATA / "dataset.jsonl").read_text().splitlines() if line.strip()]
    assert len(rows) == len({row["run_id"] for row in rows}) == 900
    assert all(row["trial_ok"] and row["heartbeat"] == "500ms" for row in rows)
    groups = defaultdict(list)
    for row in rows:
        groups[row["topology"], row["mode"], row["delay"]].append(row)

    throughput, progress, recovery, events = [], [], [], []
    for topology in ("T0", "T1", "T2", "T3", "T4"):
        for delay, display in DELAYS:
            conditions = [groups[topology, mode, delay] for mode in MODES]
            assert all(len(condition) == 30 for condition in conditions)
            prefix = [topology, display]
            throughput.append(prefix + [
                mean_sd([row["commit_throughput_observe_eps"] for row in condition])
                for condition in conditions
            ])
            progress.append(prefix + [
                str(sum(bool(row["stable_progress"]) for row in condition))
                for condition in conditions
            ] + [
                str(sum(row["client_ok_observe"] == 0 for row in condition))
                for condition in conditions
            ])
            recovered = [
                [row["recovery_time_ms"] for row in condition
                 if row["client_ok_observe"] > 0 and row.get("recovery_time_ms") is not None]
                for condition in conditions
            ]
            recovery.append(prefix + [mean_sd(values) for values in recovered]
                            + [str(len(values)) for values in recovered])
            events.append(prefix + [
                f"{mean(row[field] for row in condition):.2f}"
                for field in ("elections_observe", "term_changes_observe")
                for condition in conditions
            ])

    parts = [
        "% Generated by gen_tables.py from the full-20261014-hb500-noprevote campaign.\n",
        r"\subsection{Throughput and Progress}" + "\n",
        table(
            r"Client-observed commit throughput (commits/s; mean $\pm$ sample SD, $n=30$ per condition). The interval runs from injection to observation end and includes T3 setup.",
            "tab:throughput", "llrr",
            r"Topology & Delay (ms) & Direct & Forwarding", throughput,
        ),
        table(
            "Stable-progress and zero-success trial counts. Each condition has 30 validated trials. Zero-success trials have no successful client commits during observation.",
            "tab:progress", "llrrrr",
            r"& & \multicolumn{2}{c}{Stable progress} & \multicolumn{2}{c}{Zero successes} \\ "
            r"Topology & Delay (ms) & Direct & Forwarding & Direct & Forwarding", progress,
        ),
        "\\clearpage\n\\subsection{Recovery and Recorded Events}\n",
        table(
            r"Injection to first successful client commit (ms; mean $\pm$ sample SD), with contributing trial counts. Dashes indicate no successful commits. T3 includes restart and harness setup.",
            "tab:recovery", "llrrrr",
            r"Topology & Delay (ms) & Direct & Forwarding & Direct $n$ & Fwd.\ $n$", recovery,
        ),
        table(
            "Mean recorded election-event and term-change counts after injection ($n=30$ per condition). These sampled events are not an exhaustive count of internal Raft transitions.",
            "tab:events", "llrrrr",
            r"& & \multicolumn{2}{c}{Election events} & \multicolumn{2}{c}{Term changes} \\ "
            r"Topology & Delay (ms) & Direct & Forwarding & Direct & Forwarding", events,
        ),
    ]
    (OUT / "rq1-tables.tex").write_text("\n".join(parts), encoding="utf-8")

    timing = []
    for delay, display in DELAYS:
        starts, rates = [], []
        for row in groups["T3", "forwarding", delay]:
            timeline = json.loads((DATA / row["run_id"] / "timeline.json").read_text())
            start = timeline["client_started_ns"]
            starts.append((start - timeline["inject_at_ns"]) / 1e9)
            duration = (timeline["observe_end_ns"] - start) / 1e9
            assert duration > 0
            rates.append(row["client_ok_observe"] / duration)
        timing.append([display, mean_sd(starts), mean_sd(rates)])
    (OUT / "t3-timing-table.tex").write_text(table(
        r"T3 forwarding timing ($n=30$ per delay; mean $\pm$ sample SD). Client start is measured from injection. Throughput here uses client start to observation end; Table~\ref{tab:throughput} uses injection to observation end.",
        "tab:t3-timing", "lrr",
        r"Delay (ms) & Client start (s) & Throughput (commits/s)", timing,
    ), encoding="utf-8")
    print("Generated RQ1 and T3 timing tables from 900 validated trials.")


if __name__ == "__main__":
    main()
